// الحالة
// =====================================================

let currentType = null;
let currentQuestion = "";

let round = 0;
let truthCount = 0;
let dareCount = 0;

const questionBox =
    document.getElementById("questionBox");

const roundElement =
    document.getElementById("round");

const truthCountElement =
    document.getElementById("truthCount");

const dareCountElement =
    document.getElementById("dareCount");


// =====================================================
// اختيار سؤال
// =====================================================

function getQuestion(type) {

    currentType = type;

    const list =
        type === "truth"
            ? truthQuestions
            : dareQuestions;

    if (!list.length) {

        showMessage(
            "🎉",
            "خلصت الأسئلة",
            "اضغط «إعادة اللعبة» لبدء مجموعة جديدة"
        );

        return;
    }


    const randomIndex =
        Math.floor(Math.random() * list.length);

    currentQuestion =
        list[randomIndex];


    // إزالة السؤال لمنع التكرار
    list.splice(randomIndex, 1);


    round++;


    if (type === "truth") {
        truthCount++;
    } else {
        dareCount++;
    }


    updateStats();

    renderQuestion(type, currentQuestion);
}


// =====================================================
// عرض السؤال
// =====================================================

function renderQuestion(type, question) {

    const isTruth =
        type === "truth";


    questionBox.className =
        `question-card active ${type}`;


    questionBox.innerHTML = `

        <div class="question-type">
            ${isTruth ? "🎤 سؤال صراحة" : "⚡ تحدي جرأة"}
        </div>

        <div class="question-icon">
            ${isTruth ? "🎤" : "⚡"}
        </div>

        <h2>
            ${question}
        </h2>

        <div class="question-line"></div>

        <p>
            ${
                isTruth
                ? "جاوب بصراحة وبالقدر اللي يناسبك ❤️"
                : "نفّذ التحدي بطريقة آمنة وممتعة 😎"
            }
        </p>
    `;


    // Animation restart
    questionBox.style.animation = "none";

    requestAnimationFrame(() => {

        questionBox.style.animation =
            "cardIn .45s ease";
    });
}


// =====================================================
// سؤال جديد من نفس النوع
// =====================================================

function newQuestion() {

    if (!currentType) {

        getQuestion("truth");

        return;
    }


    getQuestion(currentType);
}


// =====================================================
// رسالة
// =====================================================

function showMessage(icon, title, text) {

    questionBox.className =
        "question-card idle";


    questionBox.innerHTML = `

        <div class="question-icon">
            ${icon}
        </div>

        <h2>${title}</h2>

        <p>${text}</p>

    `;
}


// =====================================================
// تحديث الإحصائيات
// =====================================================

function updateStats() {

    roundElement.textContent =
        round;

    truthCountElement.textContent =
        truthCount;

    dareCountElement.textContent =
        dareCount;
}


// =====================================================
// إعادة اللعبة
// =====================================================

function resetGame() {

    // إعادة الأسئلة الأصلية
    // من خلال إعادة تحميل الصفحة
    location.reload();
}


// =====================================================
// تأثير النجوم
// =====================================================

function createStars() {

    const starsContainer =
        document.querySelector(".stars");


    const fragment =
        document.createDocumentFragment();


    for (let i = 0; i < 90; i++) {

        const star =
            document.createElement("span");


        star.className = "star";


        star.style.left =
            `${Math.random() * 100}%`;

        star.style.top =
            `${Math.random() * 100}%`;


        star.style.animationDelay =
            `${Math.random() * 3}s`;


        star.style.animationDuration =
            `${1 + Math.random() * 3}s`;


        fragment.appendChild(star);
    }


    starsContainer.appendChild(fragment);
}


// =====================================================
// تشغيل النجوم
// =====================================================

createStars();

updateStats();

